export const FAQ_CATEGORIES: FaqCategory[] = ['料金', '導入', '機能', 'データとセキュリティ', '契約'];

export function faqByCategory(): { cat: FaqCategory; items: FaqItem[] }[] {
  return FAQ_CATEGORIES
    .map(cat => ({ cat, items: CRM_FAQ.filter(item => item.cat === cat) }))
    .filter(group => group.items.length > 0);
}

// ── 未決のまま載せていない質問（2026-08-21）─────────────────────
// 事実が確定していないため、意図的に書いていない。決まったら足すこと。
// 購入前の人が一番気にするのは1つ目なので、優先度が高い。
//   1. 契約期間と解約条件（最低利用期間／月次で解約できるか／日割りの有無）
//   2. サポートの窓口と応答時間（メールのみか／何時間以内に返すか）
//   3. セキュリティ認証（ISMS・SOC2などの取得状況。無いなら「無い」と書くほうが誠実）
//   4. 稼働率の保証（SLAを出すか）
//   5. AI利用量の上限の具体値（いまは「上限がある」とだけ書き、数字は伏せている）
